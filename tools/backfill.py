def write_safe(path: Path, text: str, tmpdir: Path):
    """中文路径下的文件有时被预览面板或沙箱占用，直接写会 PermissionError 13。
    兜底：写到 _tmp/ 再删旧文件、顶替过去。"""
    try:
        path.write_text(text, encoding="utf-8")
        return "直接写入"
    except PermissionError:
        tmpdir.mkdir(exist_ok=True)
        tmp = tmpdir / (path.name + ".new")
        tmp.write_text(text, encoding="utf-8")
        import os
        import shutil
        os.remove(path)
        shutil.move(str(tmp), str(path))
        return "替换法写入"


def main():
    dry = "--check" in sys.argv
    tmpdir = ROOT / "_tmp"

    targets = (sorted((ROOT / "book").glob("*.md")) +
               sorted((ROOT / "docs" / "核实记录").glob("*.md")))
    counts = {old: 0 for old, _ in RULES}
    changed = 0

    for path in targets:
        text = path.read_text(encoding="utf-8")
        orig = text
        applied = []
        for old, new in RULES:
            n = text.count(old)
            if n:
                text = text.replace(old, new)
                counts[old] += n
                applied.append(f"{n}x  {old[:54]}")
        # 追加说明段（幂等）
        rel = path.relative_to(ROOT).as_posix()
        note = NOTES.get(rel)
        if note and note.splitlines()[0] not in text:
            text = text.rstrip("\n") + "\n\n" + note
            applied.append("追加「来源回填」说明段")

        if text == orig:
            continue
        changed += 1
        if dry:
            print(f"[将改] {rel}")
        else:
            how = write_safe(path, text, tmpdir)
            print(f"[已改] {rel}（{how}）")
        for a in applied:
            print(f"         {a}")

    print(f"\n{'将改动' if dry else '改动'}文件 {changed} 个。规则命中：")
    dead = []
    for old, _ in RULES:
        if not counts[old]:
            dead.append(old)
        print(f"  {'OK' if counts[old] else '!! 0 次':6s} {counts[old]:>3d}x  {old[:60]}")

    if dead:
        print("\n!! 下面这些串一次都没命中。可能是已经改过（幂等正常），"
              "也可能原文与预期不符，请人工确认：")
        for d in dead:
            print("   - " + d)

    if not dry:
        print("\n下一步：python tools/check-body.py --urls")
    return 0


if __name__ == "__main__":
    sys.exit(main())
